namespace AIValidation.Api.Data.Entities;

/// <summary>
/// KnowledgeItem Entity - General knowledge data model.
///
/// Mục đích:
/// - Store standardized medical knowledge in database
/// - Support multiple knowledge types (ICD, DVKT, Drugs, etc.)
/// - Enable efficient search and retrieval
/// - Maintain audit trail with timestamps
///
/// Structure:
/// - Unified entity model (not separate ICD, DVKT, Drug tables)
/// - Category indicates knowledge type
/// - Code: Standard code (ICD-10, procedure code, drug code)
/// - Name: Display name
/// - Content: Full description or details
/// - Metadata: Timestamps and soft delete flag
///
/// Design:
/// - Simple, flat structure
/// - Category-based type discrimination
/// - Suitable for RAG (Retrieval Augmented Generation)
/// - Extensible: New categories without schema changes
///
/// Examples:
/// - ICD: Category="ICD", Code="I10", Name="Essential hypertension"
/// - Procedure: Category="DVKT", Code="99291", Name="Critical care first 30-74 minutes"
/// - Drug: Category="Drug", Code="AZT", Name="Zidovudine (AZT)"
/// </summary>
public class KnowledgeItem
{
    /// <summary>
    /// Primary key - Unique identifier.
    /// 
    /// Database:
    /// - Column: id
    /// - Type: bigint (IDENTITY)
    /// - Auto-generated by database
    /// </summary>
    public long Id { get; set; }

    /// <summary>
    /// Knowledge category - Type discriminator.
    ///
    /// Values:
    /// - "ICD": International Classification of Diseases
    /// - "DVKT": Dịch vụ kỹ thuật (Medical procedures)
    /// - "Drug": Drug/medication codes
    /// - Custom categories as needed
    ///
    /// Database:
    /// - Column: category
    /// - Type: varchar(50)
    /// - Required: Yes
    /// - Indexed: Yes (for filtering by type)
    /// </summary>
    public required string Category { get; set; }

    /// <summary>
    /// Standard code for this knowledge item.
    ///
    /// Examples:
    /// - ICD-10 code (e.g., "I10")
    /// - Procedure code (e.g., "99291")
    /// - Drug code (e.g., "AZT")
    /// - Custom codes as needed
    ///
    /// Database:
    /// - Column: code
    /// - Type: varchar(100)
    /// - Required: Yes
    /// - Indexed: Yes (for direct lookup)
    /// - Unique: False (same code in different categories)
    /// </summary>
    public required string Code { get; set; }

    /// <summary>
    /// Human-readable name or title.
    ///
    /// Examples:
    /// - "Essential hypertension"
    /// - "Acute exacerbation of asthma"
    /// - "Zidovudine (AZT)"
    /// - "Blood pressure measurement"
    ///
    /// Database:
    /// - Column: name
    /// - Type: varchar(255)
    /// - Required: Yes
    /// - Used: Display, search
    /// </summary>
    public required string Name { get; set; }

    /// <summary>
    /// Full content or description.
    ///
    /// Content:
    /// - Detailed description
    /// - Clinical notes
    /// - Related information
    /// - Guidelines or instructions
    /// - References
    ///
    /// Used for:
    /// - RAG context in LLM prompts
    /// - Validation details
    /// - User information
    ///
    /// Database:
    /// - Column: content
    /// - Type: text (unlimited)
    /// - Required: Yes
    /// </summary>
    public required string Content { get; set; }

    /// <summary>
    /// Soft delete flag - Logical deletion.
    ///
    /// Values:
    /// - true: Active, included in queries
    /// - false: Inactive/deleted, excluded from queries
    ///
    /// Purpose:
    /// - Maintain data integrity
    /// - Preserve historical audit trail
    /// - Avoid accidental data loss
    /// - Enable data recovery
    ///
    /// Default: true (active)
    ///
    /// Database:
    /// - Column: is_active
    /// - Type: boolean
    /// - Default: true
    /// - Used: WHERE clause in queries
    /// </summary>
    public bool IsActive { get; set; }

    /// <summary>
    /// Timestamp when entity was created.
    ///
    /// Format:
    /// - UTC datetime
    /// - Set by database (CURRENT_TIMESTAMP)
    /// - Never updated after creation
    ///
    /// Purpose:
    /// - Audit trail
    /// - Track data origin
    /// - Sort by creation order
    ///
    /// Database:
    /// - Column: created_at
    /// - Type: timestamp with time zone
    /// - Default: CURRENT_TIMESTAMP
    /// </summary>
    public DateTime CreatedAt { get; set; }

    /// <summary>
    /// Timestamp when entity was last updated.
    ///
    /// Format:
    /// - UTC datetime
    /// - Set to CURRENT_TIMESTAMP on create and update
    /// - Updated each time entity changes
    ///
    /// Purpose:
    /// - Audit trail
    /// - Track data modifications
    /// - Identify stale data
    ///
    /// Database:
    /// - Column: updated_at
    /// - Type: timestamp with time zone
    /// - Default: CURRENT_TIMESTAMP
    /// - Updated on row changes
    /// </summary>
    public DateTime UpdatedAt { get; set; }

    /// <summary>
    /// Extended metadata stored as JSONB.
    ///
    /// Purpose:
    /// - Store flexible, unstructured data
    /// - Avoid schema changes for new attributes
    /// - Support future extensibility
    /// - Enable complex filtering in PostgreSQL
    ///
    /// Examples:
    /// {
    ///   "gender": "Female",
    ///   "minAge": 18,
    ///   "maxAge": null,
    ///   "pregnancyOnly": true,
    ///   "safetyCategory": "A",
    ///   "contraindications": ["kidney_disease", "liver_disease"]
    /// }
    ///
    /// Usage:
    /// - ICD-specific gender restrictions
    /// - Drug safety categories (FDA pregnancy categories)
    /// - Age-based restrictions (pediatric, geriatric)
    /// - Pregnancy safety information
    /// - Common contraindications
    /// - Insurance-specific rules
    /// - Clinical guideline references
    ///
    /// Database:
    /// - Column: metadata
    /// - Type: jsonb
    /// - Default: NULL
    /// - Nullable: Yes
    /// - Indexed: No (future: GIN index for JSON queries)
    ///
    /// Future:
    /// - Add GIN index for efficient JSON queries
    /// - Use PostgreSQL JSON operators (@>, ->, etc.)
    /// - Support complex filtering rules
    /// </summary>
    public Dictionary<string, object>? Metadata { get; set; }
}
